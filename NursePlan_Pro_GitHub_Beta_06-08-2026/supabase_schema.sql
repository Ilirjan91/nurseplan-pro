alter table public.mitarbeitende enable row level security;
alter table public.dienstplaene enable row level security;
alter table public.einstellungen enable row level security;
alter table public.vorgaben enable row level security;
alter table public.vorlagen enable row level security;
alter table public.feedback enable row level security;

