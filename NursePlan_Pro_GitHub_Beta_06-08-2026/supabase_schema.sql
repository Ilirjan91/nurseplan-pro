-- ---------------------------------------------------------------------------
-- 1. Benutzerprofile
-- ---------------------------------------------------------------------------

create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    full_name text not null default '',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

-- Für jedes neue Auth-Konto automatisch ein Profil anlegen.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
    insert into public.profiles (id, full_name)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'full_name', '')
    )
    on conflict (id) do nothing;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute procedure public.handle_new_user();

-- ---------------------------------------------------------------------------
-- 2. NursePlan-Pro-Tabellen
-- Jede Zeile besitzt eine owner_id. Sie verbindet die Daten mit dem Konto.
-- ---------------------------------------------------------------------------

create table if not exists public.mitarbeitende (
    id bigint generated by default as identity primary key,
    owner_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    name text not null,
    stellenanteil text not null,
    wochenstunden numeric(7,2) not null,
    qualifikation text not null,
    erfahrung text not null,
    nachtdienst text not null,
    monatssollstunden numeric(7,2),
    schutzstatus text not null default 'Keiner',
    feste_dienstart text not null default 'Alle Dienste',
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (id, owner_id)
);

create table if not exists public.dienstplaene (
    id bigint generated by default as identity primary key,
    owner_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    name text not null,
    startdatum date not null,
    zeitraum integer not null,
    plan_json jsonb not null,
    erstellt_am timestamptz not null default now(),
    aktualisiert_am timestamptz not null default now(),
    unique (id, owner_id)
);

create table if not exists public.einstellungen (
    owner_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    schluessel text not null,
    wert_json jsonb not null,
    aktualisiert_am timestamptz not null default now(),
    primary key (owner_id, schluessel)
);

create table if not exists public.vorgaben (
    id bigint generated by default as identity primary key,
    owner_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    mitarbeitende_id bigint not null,
    code text not null,
    startdatum date not null,
    enddatum date not null,
    bemerkung text not null default '',
    erstellt_am timestamptz not null default now(),
    unique (id, owner_id),
    constraint vorgaben_gueltiger_zeitraum check (enddatum >= startdatum),
    constraint vorgaben_mitarbeitende_des_kontos
        foreign key (mitarbeitende_id, owner_id)
        references public.mitarbeitende(id, owner_id)
        on delete cascade
);

create table if not exists public.vorlagen (
    id bigint generated by default as identity primary key,
    owner_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    name text not null,
    beschreibung text not null default '',
    kategorie text not null default 'Eigene Vorlage',
    daten_json jsonb not null,
    erstellt_am timestamptz not null default now(),
    aktualisiert_am timestamptz not null default now(),
    unique (id, owner_id)
);

create table if not exists public.feedback (
    id bigint generated by default as identity primary key,
    owner_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    kategorie text not null,
    bewertung integer not null,
    betreff text not null,
    nachricht text not null,
    kontakt_erlaubt boolean not null default true,
    kontakt_email text not null default '',
    status text not null default 'Neu',
    erstellt_am timestamptz not null default now(),
    constraint feedback_kategorie_gueltig
        check (kategorie in ('Idee', 'Problem', 'Frage', 'Lob')),
    constraint feedback_bewertung_gueltig
        check (bewertung between 1 and 5),
    constraint feedback_betreff_laenge
        check (char_length(betreff) between 3 and 120),
    constraint feedback_nachricht_laenge
        check (char_length(nachricht) between 10 and 3000)
);

create index if not exists idx_mitarbeitende_owner
    on public.mitarbeitende(owner_id);
create index if not exists idx_dienstplaene_owner_aktualisiert
    on public.dienstplaene(owner_id, aktualisiert_am desc);
create index if not exists idx_vorgaben_owner_zeitraum
    on public.vorgaben(owner_id, startdatum, enddatum);
create index if not exists idx_vorlagen_owner_aktualisiert
    on public.vorlagen(owner_id, aktualisiert_am desc);
create index if not exists idx_feedback_owner_erstellt
    on public.feedback(owner_id, erstellt_am desc);

-- Zeitstempel bei Änderungen automatisch aktualisieren.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

create or replace function public.set_aktualisiert_am()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
    new.aktualisiert_am = now();
    return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
    before update on public.profiles
    for each row execute procedure public.set_updated_at();

drop trigger if exists mitarbeitende_set_updated_at on public.mitarbeitende;
create trigger mitarbeitende_set_updated_at
    before update on public.mitarbeitende
    for each row execute procedure public.set_updated_at();

drop trigger if exists dienstplaene_set_aktualisiert_am on public.dienstplaene;
create trigger dienstplaene_set_aktualisiert_am
    before update on public.dienstplaene
    for each row execute procedure public.set_aktualisiert_am();

drop trigger if exists einstellungen_set_aktualisiert_am on public.einstellungen;
create trigger einstellungen_set_aktualisiert_am
    before update on public.einstellungen
    for each row execute procedure public.set_aktualisiert_am();

drop trigger if exists vorlagen_set_aktualisiert_am on public.vorlagen;
create trigger vorlagen_set_aktualisiert_am
