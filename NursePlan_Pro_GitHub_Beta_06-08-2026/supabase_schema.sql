    for each row execute procedure public.set_aktualisiert_am();

-- ---------------------------------------------------------------------------
-- 3. Rechte und Row Level Security (RLS)
-- Nicht angemeldete Besucher erhalten keinen Zugriff auf Fachdaten.
-- Angemeldete Benutzer dürfen ausschließlich ihre eigenen Zeilen verwenden.
-- ---------------------------------------------------------------------------

