grant select, insert, update, delete on public.mitarbeitende to authenticated;
grant select, insert, update, delete on public.dienstplaene to authenticated;
grant select, insert, update, delete on public.einstellungen to authenticated;
grant select, insert, update, delete on public.vorgaben to authenticated;
grant select, insert, update, delete on public.vorlagen to authenticated;
grant select, insert on public.feedback to authenticated;
grant usage, select on all sequences in schema public to authenticated;

